// Pasos para configurar un snippet en VS Code
/**
 * 1. Abrimos la paleta de comandos (Ctrl + Shift + P)
 * 2. Buscamos la opción "Configure User Snippets"
 * 3. Seleccionamos configurar snippets (conviene hacerlo de forma global)
 * 4. Elegimos la opción "New Global Snippets file" o un archivo de lenguaje existente
 * 5. Seleccionamos el lenguaje que vamos a usar para el snippet (ej: javascriptreact)
 * 6. Le asignamos un nombre al snippet (nombre descriptivo)
 * 7. Definimos el prefijo que activará el snippet
 * 8. Completamos el archivo JSON respetando la sintaxis:
 *    - Comillas dobles ("") en cada línea del body
 *    - Separar cada línea con coma
 *    - Mantener un único objeto raíz {}
 */

